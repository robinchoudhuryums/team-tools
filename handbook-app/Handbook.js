/** HB1.4 — the search settings Team Tools keeps in ITS Script Properties (the
 *  synonym groups, and the auto-tag rules the search signal's vocabulary is
 *  built from) reach this project through the KbSearchConfig tab Team Tools
 *  mirrors them to. Read once per HB_CACHE_TTL; a missing or unreadable mirror
 *  is "none" — search still runs, without them, as Team Tools does with an
 *  empty property. */
let _hbSearchCfg = null;
function hbSearchConfig_() {
  if (_hbSearchCfg) return _hbSearchCfg;
  const cache = CacheService.getScriptCache();
  let raw = null;
  try { raw = cache.get(HB_SEARCH_CFG_CACHE_KEY); } catch (e) {}
  if (raw == null) {
    raw = '';
    try {
      const sheet = getKbSS_().getSheetByName(KB_SEARCH_CONFIG_TAB);
      if (sheet && sheet.getLastRow() >= 2) raw = String(sheet.getRange(2, 1).getValue() || '');
      try { cache.put(HB_SEARCH_CFG_CACHE_KEY, raw, HB_CACHE_TTL); } catch (e) {}
    } catch (e) { raw = ''; }   // a failed read is not cached
  }
  let cfg = {};
  try { cfg = raw ? (JSON.parse(raw) || {}) : {}; } catch (e) { cfg = {}; }
  _hbSearchCfg = cfg;
  return cfg;
}
function getKbSearchSynonyms_() { return kbSynonymGroups_(hbSearchConfig_().synonyms); }
function getAutoTagRules_() { return autoTagRulesNormalize_(hbSearchConfig_().tags); }

/** A tab this app appends to, created with its headers the first time. Two
 *  first appends at once both try to create it; the loser reads the winner's. */
function hbAppendTab_(name, headers) {
  const ss = getKbSS_();
  let sheet = ss.getSheetByName(name);
  if (sheet) return sheet;
  try {
    sheet = ss.insertSheet(name);
    sheet.appendRow(sheetSafeRow_(headers));
    return sheet;
  } catch (e) {
    sheet = ss.getSheetByName(name);
    if (sheet) return sheet;
    throw e;
  }
}
/** The search signal, for this app's searches: Team Tools' plan (vocabulary
 *  terms only, no person, once per person per term per window), appended to
 *  KbSearchSignalHb. The term rides a leading apostrophe, so a heading like
 *  "3/4" stays text (the '@' rule Team Tools keeps by formatting the cell — a
 *  format needs a position, and this app writes none). Best-effort: a failure
 *  costs the signal, never the search. */
function kbRecordSearchSignal_(emp, query, zero) {
  try {
    const fresh = kbSearchSignalPlan_(emp, query, zero);
    if (!fresh.length) return 0;
    const sheet = hbAppendTab_(KB_SEARCH_SIGNAL_HB_TAB, KB_SEARCH_SIGNAL_HEADERS);
    const now = new Date(), ts = fmtDate_(now) + ' ' + fmtTime_(now);
    fresh.forEach(function (f) { sheet.appendRow(sheetSafeRow_([ts, "'" + f.term, f.source, f.ev])); });
    kbSearchSignalSeen_(fresh);
    return fresh.length;
  } catch (err) {
    console.warn('kbRecordSearchSignal_ failed: ' + err.message);
    return 0;
  }
}

/** A JSON value through the script cache in pieces (one cache value holds
 *  100 KB) — the copied search index's chunking constants. null on a miss. */
function hbCacheGetJson_(base) {
  try {
    const cache = CacheService.getScriptCache();
    const n = parseInt(cache.get(base + 'n') || '', 10);
    if (!(n > 0)) return null;
    const keys = [];
    for (let i = 0; i < n; i++) keys.push(base + i);
    const got = cache.getAll(keys);
    if (!keys.every(function (k) { return typeof got[k] === 'string'; })) return null;
    return JSON.parse(keys.map(function (k) { return got[k]; }).join(''));
  } catch (e) { return null; }
}
function hbCachePutJson_(base, value) {
  try {
    const json = JSON.stringify(value), put = {};
    let n = 0;
    for (let at = 0; at < json.length; at += KB_INDEX_CHUNK) put[base + (n++)] = json.substring(at, at + KB_INDEX_CHUNK);
    if (n <= KB_INDEX_MAX_CHUNKS) { put[base + 'n'] = String(n); CacheService.getScriptCache().putAll(put, HB_CACHE_TTL); }
  } catch (e) {}
}

