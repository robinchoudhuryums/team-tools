/* The handbook app's server (HB1.2, operator 2026-10-28).
 *
 * A SEPARATE Apps Script project from Team Tools: any employee signed in to the
 * org's domain may open it (the deployment's access is the domain; it runs as
 * the deployer, so readers need no access to the spreadsheet). It READS the
 * same Knowledge Base spreadsheet Team Tools publishes the handbook into;
 * importing and publishing stay in Team Tools' Admin. Since HB1.4 it WRITES two
 * things, both by appendRow (an atomic append — another project's ScriptLock
 * cannot serialise with this one's, so nothing here writes by position): a
 * reader's section feedback into KbFeedback (Team Tools' tab, the export's
 * source), and its searches' vocabulary terms into its own KbSearchSignalHb tab
 * (Team Tools' signal report and nightly purge read it beside their own).
 *
 * TWO FILES, one global scope (as in Team Tools):
 *   kb_shared.js  GENERATED by scripts/handbook-sync.mjs — Team Tools'
 *                 handbook readers copied VERBATIM, with every declaration
 *                 they reach. Never edit it: edit web-app/ and run
 *                 `npm run handbook:sync`. CI fails while it differs.
 *   Handbook.js   this file — the ENVIRONMENT the copied code expects (who is
 *                 asking, which spreadsheet, the KB tab, today), and the public
 *                 endpoints the shared reader calls.
 *
 * The copied code calls getEmployeeInfo_, getKbSS_, getOrCreateKbSheet_,
 * fmtDate_, fmtTime_, getKbSearchSynonyms_, getAutoTagRules_ and
 * kbRecordSearchSignal_ by those names; this file supplies them, and the sync stops its
 * dependency walk at every name declared here. A Team Tools endpoint the
 * handbook serves is copied under a private name (`tt` + its name + `_`, the
 * sync's RENAMES table) so the public name here decides what the handbook
 * does with it — getReferenceItem, for one, serves handbook sections only.
 *
 * Every public function below (a name that does not end in `_` is reachable
 * by google.script.run — g143) is pinned by name in test/client/run.js.
 *
 * Freshness: this project's script cache is its own, so Team Tools' cache
 * clears never reach it. Everything cached here lives HB_CACHE_TTL seconds
 * (the meta through the copied kbManualMetaCached_, KB_CACHE_TTL — the same
 * five minutes), so a publish in Team Tools shows here within five minutes.
 * Images are cached by content hash and are never stale. */

const HB_KB_SS_PROP = 'HANDBOOK_KB_SS_ID';
const HB_CACHE_TTL = 300;
const HB_PARTS_CACHE_KEY = 'hb_parts_v2:';   // v2 (HB1.3): the answer carries its stamp
const HB_NOT_HERE = 'is not available in the handbook app yet.';
const HB_SEARCH_CFG_CACHE_KEY = 'hb_search_cfg_v1';

/** HB1.3: the page, with the link's section (`?s=6.9.3`) — the page cannot
 *  read its own address (g107), so the server hands it over. Only a value
 *  shaped like a section number survives; the page resolves it. */
function doGet(e) {
  const t = HtmlService.createTemplateFromFile('index');
  const s = String((e && e.parameter && e.parameter.s) || '').trim();
  t.hbParams = { s: /^[\w.§ -]{1,24}$/.test(s) ? s : '' };
  return t.evaluate()
    .setTitle('UMS Handbook')
    .addMetaTag('viewport', 'width=device-width, initial-scale=1');
}
function include(filename) {
  return HtmlService.createHtmlOutputFromFile(filename).getContent();
}

