/** Who is asking. Any signed-in account the deployment lets in (the domain)
 *  is a reader; nobody is an admin here, so a draft is never served — the
 *  copied readers hide drafts from a caller whose isAdmin is false. */
function getEmployeeInfo_() {
  let email = '';
  try { email = String(Session.getActiveUser().getEmail() || '').trim().toLowerCase(); } catch (e) { email = ''; }
  if (!email) return null;
  // id: the signal's per-person dedupe key hashes it (never stored); there is
  // no roster here, so the address is the id.
  return { id: email, email: email, isAdmin: false, isManager: false };
}
let _hbKbSS = null;
/** The Knowledge Base spreadsheet, by the HANDBOOK_KB_SS_ID Script Property —
 *  unset is said by name, never a fallback (g122). */
