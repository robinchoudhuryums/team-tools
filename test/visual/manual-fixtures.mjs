// Manual fixes E (2026-10-09) — refresh the visual matrix's procedures-manual
// fixtures from a REAL manual.json, so the reader is photographed on the
// manual's own text, numbers and images rather than on a fixture that drifted
// (the hand-written 0.10, 0.11 and 10.1 still carried the pre-renumber
// "0.10.2 Before you transfer", "Part 0" and router "5.2 if it's scheduled"
// for a cycle after the October renumber).
//
//   node test/visual/manual-fixtures.mjs <path to manual.json>
//
// Rewrites, and nothing else:
//   - mock.js between the MANUAL-FIXTURES markers: REAL_MANUAL (the sections
//     below, verbatim) and REAL_META (version, build date, the router rows the
//     scenarios use, and the changelog entries for the fixture sections and the
//     newest few overall);
//   - manual-images.json: every image those sections name, plus the two the
//     synthetic 0.11 feature fixture shows.
// The synthetic 0.11 (in mock.js's manualSection) stays hand-written on
// purpose: no real section carries a nested list, a Critical callout, a Script
// snippet, HCPCS codes and a cross-chapter link together, and the scenarios
// photograph each of those. Its headings and link targets are the real ones.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// man-c-5 is Chapter 05's quick card — its masthead shows it (M14, Phase 8).
// 0.2 and 6.2 are the router's own targets: the router lists a row only when
// the reader can see a section it points at.
const SECTIONS = ['man-0-2', 'man-0-10', 'man-3-8', 'man-5-1', 'man-5-2', 'man-6-2', 'man-10-4', 'man-c-5'];
const ROUTER_QS = ['Where is my equipment?', "You're waiting on my doctor?", 'How much will this cost me?'];
// searchReference's section hit: the real table row that answers "waiting on
// my doctor", under its own heading (the router hit above points at the same).
const SEARCH = { id: 'man-0-2', anchor: '0.2.2', match: 'Fax History' };
// manualSection('man-0-11') shows these two; 'icon-retired-chair' is left out
// on purpose — it is the "not imported" chip the images scenario photographs.
const SYNTHETIC_IMAGES = ['fig-o2-regulator', 'thumb-mm-image43'];
const BEGIN = '  // MANUAL-FIXTURES:BEGIN — generated by test/visual/manual-fixtures.mjs; do not hand-edit';
const END = '  // MANUAL-FIXTURES:END';

const src = process.argv[2];
if (!src) { console.error('usage: node test/visual/manual-fixtures.mjs <manual.json>'); process.exit(2); }
const man = JSON.parse(fs.readFileSync(src, 'utf8'));
const byId = new Map(man.articles.map((a) => [a.Id, a]));

const real = {};
for (const id of SECTIONS) {
  const a = byId.get(id);
  if (!a) throw new Error(id + ' is not in ' + src + ' — update SECTIONS (and the scenarios that open it)');
  real[id] = { id, title: a.Title, department: a.Department, sortOrder: a.SortOrder, bodyMd: a.BodyMd };
}
const router = ROUTER_QS.map((q) => {
  const r = man.router.find((x) => x.q === q);
  if (!r) throw new Error('router row "' + q + '" is not in ' + src);
  return r;
});
const ids = new Set(SECTIONS.concat(['man-0-11']));
const titles = {};
for (const r of router) for (const x of r.t) {
  const a = byId.get(x.id);
  if (!a) throw new Error('router target ' + x.id + ' is not in ' + src);
  titles[x.id] = { title: a.Title, department: a.Department };
}
const sa = byId.get(SEARCH.id), sec = sa && sa.BodyMd.split(/^(?=## )/m).find((s) => s.startsWith('## ' + SEARCH.anchor + ' '));
const rows = sec ? sec.split('\n').filter((l) => l.startsWith('|')) : [];
const hit = rows.find((l) => l.includes(SEARCH.match));
if (!hit || rows.length < 3) throw new Error('no table row naming "' + SEARCH.match + '" under ' + SEARCH.anchor + ' in ' + SEARCH.id);
const search = { id: SEARCH.id, title: sa.Title, department: sa.Department, anchor: SEARCH.anchor,
  heading: sec.split('\n')[0].replace(/^## /, ''), chunkMd: [rows[0], rows[1], hit].join('\n') };
const meta = {
  version: man.version, built: man.built, router, titles, search,
  changelog: man.changelog.filter((c) => ids.has(c.id)),
  recent: man.changelog.slice(0, 3),
};

const mockPath = path.join(HERE, 'mock.js');
const mock = fs.readFileSync(mockPath, 'utf8');
const i = mock.indexOf(BEGIN), j = mock.indexOf(END);
if (i < 0 || j < i) throw new Error('mock.js has no MANUAL-FIXTURES markers');
const block = BEGIN + '\n  var REAL_MANUAL = ' + JSON.stringify(real, null, 1) + ';\n  var REAL_META = ' + JSON.stringify(meta, null, 1) + ';\n';
fs.writeFileSync(mockPath, mock.slice(0, i) + block + mock.slice(j));

const want = new Set(SYNTHETIC_IMAGES);
for (const id of SECTIONS) for (const m of real[id].bodyMd.matchAll(/manimg:([\w.-]+)/g)) want.add(m[1]);
const images = {}, missing = [];
for (const k of [...want].sort()) {
  const im = man.images[k];
  if (im && im.dataUri) images[k] = im.dataUri; else missing.push(k);
}
fs.writeFileSync(path.join(HERE, 'manual-images.json'), JSON.stringify(images) + '\n');
console.log('mock.js: ' + SECTIONS.length + ' real sections, ' + router.length + ' router rows, ' + meta.changelog.length + ' changelog entries (' + man.version + ', built ' + man.built + ')');
console.log('manual-images.json: ' + Object.keys(images).length + ' images' + (missing.length ? ' — NOT in the export: ' + missing.join(', ') : ''));
