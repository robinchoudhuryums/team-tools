#!/usr/bin/env node
/* The handbook app's copy of Team Tools (HB1.2, operator 2026-10-28).
 *
 * handbook-app/ is a second Apps Script project that serves the handbook to
 * every employee. It must show EXACTLY what Team Tools' Reference shows, so it
 * owns as little code as possible: the reader is Team Tools' shared partial,
 * and the server is Team Tools' handbook readers. This script makes those
 * copies, and `--check` (CI) fails while any copy differs from what it would
 * write — a copy can go stale, it cannot drift silently.
 *
 *   node scripts/handbook-sync.mjs           write the copies
 *   node scripts/handbook-sync.mjs --check   exit 1 while a copy is stale
 *   --root <dir>                              read and write under <dir> (tests)
 *
 * THE CLIENT: CLIENT_COPIES, byte for byte under a one-line banner; and since
 * HB1.3 shell_shared.html, the page declarations of SHELL_SOURCES the handbook's
 * pages use, walked the way the server is (buildShell).
 *
 * THE SERVER is DERIVED, not listed. handbook-app/Handbook.js is the hand-
 * written part: the environment Team Tools' code expects (getEmployeeInfo_,
 * getKbSS_, getOrCreateKbSheet_, fmtDate_) and the public endpoints. Every
 * name Handbook.js uses that Team Tools' server declares is copied into
 * handbook-app/kb_shared.js, with every declaration THAT reaches, walking the
 * dependency graph and stopping at any name Handbook.js declares (the
 * environment — so Team Tools' roster gate becomes the handbook's). A name
 * shaped `ttXxx_` in Handbook.js copies Team Tools' `xxx` under that private
 * name, so the handbook's public endpoint of the same name wraps it.
 * `HB_TT_CONFIG` carries the CONFIG values Handbook.js needs (CONFIG_PICKS),
 * read from CONFIG's source — literals only.
 *
 * REFUSALS (exit 1, naming the declaration): the walk reaches CONFIG (all of
 * it would ship), or a copied declaration calls a WRITE — a sheet, property,
 * lock or mail API. The handbook app reads; publishing stays in Team Tools. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as acorn from 'acorn';
import * as eslintScope from 'eslint-scope';

const argv = process.argv.slice(2);
const CHECK = argv.includes('--check');
const rootAt = argv.indexOf('--root');
const ROOT = rootAt >= 0 ? path.resolve(argv[rootAt + 1]) : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const CLIENT_COPIES = [
  'shared/script_manual_render.html',
  'kb/script_manual_diagrams.html',
  'script_icons.html',
  'styles_design_tokens.html',   // HB1.3: the reader is styled exactly as in Team Tools
  'styles.html',
];
export const SERVER_OUT = 'kb_shared.js';
/** HB1.3: the page shell — what the reader and the handbook page need from
 *  Team Tools' page (overlays, toasts, copy, printing), extracted the way the
 *  server is: a walk from what the handbook's pages use, stopping at what they
 *  declare. Sources in load order. */
export const SHELL_SOURCES = ['script_core.html', 'kb/script_kb.html'];
export const SHELL_OUT = 'shell_shared.html';
/** HB_TT_CONFIG key → the CONFIG path it is read from. */
export const CONFIG_PICKS = { TIMEZONE: 'TIMEZONE', KB_TAB: 'KB.TAB' };
/** A member call by one of these names is a write; a copied declaration that
 *  makes one is refused. CacheService's put/remove are not here: the cache is
 *  the handbook's own, and caching is how it stays cheap. */
export const WRITE_CALLS = [
  'setValue', 'setValues', 'appendRow', 'insertSheet', 'deleteSheet', 'deleteRow', 'deleteRows', 'insertRowsAfter',
  'insertRowsBefore', 'clear', 'clearContent', 'clearContents', 'setFrozenRows', 'setNumberFormat', 'setFontWeight',
  'setFormula', 'setFormulas', 'setRichTextValue', 'setRichTextValues', 'setName', 'copyTo', 'moveTo',
  'setProperty', 'setProperties', 'deleteProperty', 'deleteAllProperties',
  'sendEmail', 'createDraft', 'reply', 'replyAll', 'forward',
  'getScriptLock', 'getDocumentLock', 'getUserLock', 'waitLock', 'tryLock',
  'createFile', 'createFolder', 'setTrashed', 'addEditor', 'setSharing',
];

const BANNER_HTML = (src) => '<!-- GENERATED by scripts/handbook-sync.mjs from web-app/' + src +
  ' — do not edit; edit the source and run `npm run handbook:sync`. -->\n';

function parse(src, file) {
  try { return acorn.parse(src, { ecmaVersion: 2022, sourceType: 'script', ranges: true }); }
  catch (e) { throw new Error(file + ': ' + e.message); }
}
function walk(n, f, parent, key) {
  if (!n || typeof n.type !== 'string') return;
  f(n, parent, key);
  for (const k in n) {
    const v = n[k];
    if (Array.isArray(v)) v.forEach((x) => walk(x, f, n, k));
    else if (v && typeof v.type === 'string') walk(v, f, n, k);
  }
}
/** The FREE names a statement or a whole script uses — every reference no
 *  scope inside it declares (HB1.3: scope analysis, so a local that shares a
 *  name with a top-level declaration elsewhere is not a use of it). */
function refs(node) {
  const program = node.type === 'Program' ? node : { type: 'Program', sourceType: 'script', body: [node], range: node.range, start: node.start, end: node.end };
  const sm = eslintScope.analyze(program, { ecmaVersion: 2022, sourceType: 'script' });
  return new Set(sm.globalScope.through.map((r) => r.identifier.name));
}
function topDecls(src, file) {
  const ast = parse(src, file);
  const decls = [];
  let prevEnd = 0;
  for (const s of ast.body) {
    let names = [];
    if (s.type === 'FunctionDeclaration') names = [s.id.name];
    else if (s.type === 'VariableDeclaration') names = s.declarations.map((d) => d.id.name);
    // The comment block directly above a declaration travels with it.
    // Only from the line AFTER the previous statement: a comment trailing the
    // previous statement's own line belongs to that statement.
    const nl = src.slice(prevEnd, s.start).indexOf('\n');
    const gap = nl < 0 ? '' : src.slice(prevEnd + nl + 1, s.start);
    const lead = /^\s*(\/\/|\/\*)/.test(gap) ? gap.replace(/^(\s*\n)+/, '').replace(/\s+$/, '') : '';
    if (names.length) decls.push({ names, node: s, file, text: src.slice(s.start, s.end), lead });
    prevEnd = s.end;
  }
  return decls;
}
function configPick(decl, dotted) {
  const init = decl.node.declarations[0].init;
  let obj = init;
  for (const part of dotted.split('.')) {
    if (!obj || obj.type !== 'ObjectExpression') throw new Error('CONFIG.' + dotted + ' is not an object literal path');
    const p = obj.properties.find((q) => q.key && (q.key.name === part || q.key.value === part));
    if (!p) throw new Error('CONFIG.' + dotted + ' does not exist');
    obj = p.value;
  }
  if (!obj || obj.type !== 'Literal') throw new Error('CONFIG.' + dotted + ' is not a literal, so it cannot be copied');
  return obj.value;
}

/** PURE over the tree at `root`: every file the sync owns, as { path: content },
 *  and a report of what the server copy holds. Throws on a refusal. */
export function buildHandbook(root) {
  const web = path.join(root, 'web-app'), hb = path.join(root, 'handbook-app');
  const files = {};
  for (const rel of CLIENT_COPIES) files['handbook-app/' + rel] = BANNER_HTML(rel) + fs.readFileSync(path.join(web, rel), 'utf8');

  // Team Tools' server: the pushed files, in push order (Tests.js and
  // DevTools.js are editor-only and never copied).
  const order = JSON.parse(fs.readFileSync(path.join(web, '.clasp.json'), 'utf8')).filePushOrder.filter((f) => f.endsWith('.js'));
  const tt = [];
  for (const f of order) tt.push(...topDecls(fs.readFileSync(path.join(web, f), 'utf8'), f));
  const byName = {};
  tt.forEach((d, i) => { d.order = i; d.names.forEach((n) => { byName[n] = d; }); });

  // The hand-written side: every handbook-app .js but the generated one.
  const own = fs.readdirSync(hb).filter((f) => f.endsWith('.js') && f !== SERVER_OUT).sort();
  const hbDeclared = new Set(), hbRefs = new Set();
  for (const f of own) {
    const src = fs.readFileSync(path.join(hb, f), 'utf8');
    for (const d of topDecls(src, f)) d.names.forEach((n) => hbDeclared.add(n));
    refs(parse(src, f)).forEach((n) => hbRefs.add(n));
  }
  const renames = {};   // Team Tools name → the private name it is copied as
  const roots = [];
  for (const n of [...hbRefs].sort()) {
    if (hbDeclared.has(n)) continue;
    const m = /^tt([A-Z]\w*)_$/.exec(n);
    if (m) {
      const from = m[1].charAt(0).toLowerCase() + m[1].slice(1);
      if (!byName[from]) throw new Error('Handbook.js names ' + n + ', but Team Tools declares no ' + from);
      renames[from] = n; roots.push(from);
    } else if (byName[n]) roots.push(n);
  }
  const supplied = new Set();
  const seen = new Set(), queue = roots.slice();
  while (queue.length) {
    const n = queue.shift();
    const d = byName[n];
    if (!d || seen.has(d)) continue;
    if (d.names.includes('CONFIG')) throw new Error('The walk reached CONFIG — the whole of it would ship. Pick the value in CONFIG_PICKS instead.');
    seen.add(d);
    for (const r of refs(d.node)) {
      if (d.names.includes(r)) continue;
      if (hbDeclared.has(r)) { if (byName[r]) supplied.add(r); continue; }
      if (byName[r]) queue.push(r);
    }
  }
  const copied = [...seen].sort((a, b) => a.order - b.order);
  const writes = [];
  for (const d of copied) {
    walk(d.node, (x) => {
      if (x.type === 'CallExpression' && x.callee.type === 'MemberExpression' && !x.callee.computed &&
          WRITE_CALLS.includes(x.callee.property.name)) writes.push(d.names[0] + ' (' + d.file + ') calls .' + x.callee.property.name + '()');
    });
  }
  if (writes.length) throw new Error('The handbook app only reads, but a copied declaration writes:\n  ' + writes.join('\n  '));

  const cfgDecl = byName.CONFIG;
  const picks = Object.keys(CONFIG_PICKS).map((k) => '  ' + k + ': ' + JSON.stringify(configPick(cfgDecl, CONFIG_PICKS[k])) + ',   // CONFIG.' + CONFIG_PICKS[k]);
  const renamed = Object.keys(renames).sort();
  let out = '/* GENERATED by scripts/handbook-sync.mjs — do not edit. Edit web-app/ and run `npm run handbook:sync`;\n' +
    ' * CI fails while this file differs from what the sync would write.\n' +
    ' *\n' +
    ' * Team Tools\' handbook readers, verbatim from ' + [...new Set(copied.map((d) => d.file))].join(', ') + ',\n' +
    ' * with every declaration they reach (' + copied.length + ' in all).\n' +
    ' * Copied under a private name: ' + (renamed.map((n) => n + ' → ' + renames[n]).join(', ') || 'none') + '.\n' +
    ' * Supplied by Handbook.js instead of copied: ' + ([...supplied].sort().join(', ') || 'none') + '. */\n\n' +
    'const HB_TT_CONFIG = Object.freeze({\n' + picks.join('\n') + '\n});\n';
  for (const d of copied) {
    let text = d.text;
    for (const n of d.names) {
      if (renames[n]) text = text.replace(new RegExp('^function ' + n + '\\('), 'function ' + renames[n] + '(');
    }
    out += '\n' + (d.lead ? d.lead + '\n' : '') + text + '\n';
  }
  files['handbook-app/' + SERVER_OUT] = out;

  const client = buildShell(web, hb, files, tt, hbDeclared);
  return { files, report: { copied: copied.map((d) => d.names.join(',')), renames, supplied: [...supplied].sort(), roots, client } };
}

/** The script blocks of a page partial. A block holding a scriptlet (`<?`) is
 *  template, not script, and is not parsed. */
function scriptBlocks(src) {
  return [...src.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map((m) => m[1]).filter((js) => js.indexOf('<?') < 0);
}
function htmlFilesUnder(dir, rel) {
  const out = [];
  for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
    const r = rel ? rel + '/' + e.name : e.name;
    if (e.isDirectory()) out.push(...htmlFilesUnder(dir, r));
    else if (e.name.endsWith('.html')) out.push(r);
  }
  return out;
}
/** HB1.3 — handbook-app/shell_shared.html: every Team Tools page declaration
 *  (SHELL_SOURCES) the handbook's pages use, with all they reach, stopping at
 *  anything a handbook page or a copied partial declares. Refuses a reach into
 *  Reference's state, and a call to a Team Tools server function the handbook
 *  app does not serve. */
function buildShell(web, hb, files, ttServer, hbServerDeclared) {
  const generated = new Set(CLIENT_COPIES.concat([SHELL_OUT]));
  const own = htmlFilesUnder(hb, '').filter((f) => !generated.has(f)).sort();
  const pageDeclared = new Set(), pageRefs = new Set();
  const pageSources = own.map((f) => ({ f, src: fs.readFileSync(path.join(hb, f), 'utf8') }))
    .concat(CLIENT_COPIES.map((f) => ({ f, src: fs.readFileSync(path.join(web, f), 'utf8') })));
  for (const { f, src } of pageSources) {
    for (const js of scriptBlocks(src)) {
      for (const d of topDecls(js, f)) d.names.forEach((n) => pageDeclared.add(n));
      refs(parse(js, f)).forEach((n) => pageRefs.add(n));
    }
  }
  const decls = [];
  SHELL_SOURCES.forEach((f) => scriptBlocks(fs.readFileSync(path.join(web, f), 'utf8')).forEach((js) => decls.push(...topDecls(js, f))));
  const byName = {};
  decls.forEach((d, i) => { d.order = i; d.names.forEach((n) => { if (!byName[n]) byName[n] = d; }); });
  const roots = [...pageRefs].filter((n) => !pageDeclared.has(n) && byName[n]).sort();
  const supplied = new Set(), seen = new Set(), queue = roots.slice();
  while (queue.length) {
    const d = byName[queue.shift()];
    if (!d || seen.has(d)) continue;
    if (d.names.includes('KB_STATE')) throw new Error('The page walk reached KB_STATE — Reference\'s state. The handbook host supplies state through MANUAL_HOST.');
    seen.add(d);
    for (const r of refs(d.node)) {
      if (d.names.includes(r)) continue;
      if (pageDeclared.has(r)) { if (byName[r]) supplied.add(r); continue; }
      if (byName[r]) queue.push(r);
    }
  }
  const copied = [...seen].sort((a, b) => a.order - b.order);
  // A server call in the copy must be one the handbook app answers.
  const ttPublic = new Set(ttServer.filter((d) => d.node.type === 'FunctionDeclaration' && !/_$/.test(d.names[0])).map((d) => d.names[0]));
  const hbPublic = new Set([...hbServerDeclared].filter((n) => !/_$/.test(n)));
  const calls = [];
  for (const d of copied) {
    walk(d.node, (x) => {
      if (x.type === 'CallExpression' && x.callee.type === 'MemberExpression' && !x.callee.computed) {
        const n = x.callee.property.name;
        if (ttPublic.has(n) && !hbPublic.has(n)) calls.push(d.names[0] + ' (' + d.file + ') calls the server\'s ' + n + '()');
      }
    });
  }
  if (calls.length) throw new Error('The page copy calls a server function the handbook app does not serve:\n  ' + calls.join('\n  '));
  let out = '<!-- GENERATED by scripts/handbook-sync.mjs from web-app/' + SHELL_SOURCES.join(' and web-app/') + ' — do not edit;\n' +
    '     edit the source and run `npm run handbook:sync`. -->\n<script>\n' +
    '// The page shell: Team Tools\' declarations the handbook\'s pages use, verbatim,\n' +
    '// with every declaration they reach (' + copied.length + ' in all).\n' +
    '// Supplied by the handbook\'s pages instead of copied: ' + ([...supplied].sort().join(', ') || 'none') + '.\n';
  for (const d of copied) out += '\n' + (d.lead ? d.lead + '\n' : '') + d.text + '\n';
  files['handbook-app/' + SHELL_OUT] = out + '</script>\n';
  return { copied: copied.map((d) => d.names.join(',')), supplied: [...supplied].sort(), roots };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  let built;
  try { built = buildHandbook(ROOT); }
  catch (e) { console.error('handbook-sync: ' + e.message); process.exit(1); }
  const stale = [];
  for (const [rel, content] of Object.entries(built.files)) {
    const abs = path.join(ROOT, rel);
    const cur = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (cur === content) continue;
    if (CHECK) { stale.push(rel); continue; }
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
    console.log('handbook-sync: wrote ' + rel);
  }
  if (argv.includes('--json')) console.log(JSON.stringify(built.report));
  if (stale.length) {
    console.error('handbook-sync: ' + stale.length + ' copy(ies) in handbook-app/ differ from web-app/ — run `npm run handbook:sync` and commit:\n  ' + stale.join('\n  '));
    process.exit(1);
  }
  if (CHECK) console.log('handbook-sync: handbook-app/ matches web-app/ (' + Object.keys(built.files).length + ' files, ' + built.report.copied.length + ' server and ' + built.report.client.copied.length + ' page declarations).');
}
