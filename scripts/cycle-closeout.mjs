#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// cycle-closeout.mjs — the cycle close-out, scripted (cycle 25 E5, ST5).
//
// The close-out was a hand procedure (CLAUDE.md "Cycle State & Memory"): move
// the finished cycle's STATE block into HISTORY.md, reset STATE from the
// template, and bring PROJECT_HEALTH's standing and Score History up to the
// reflection. Each step went stale on its own: PROJECT_HEALTH's Current
// Standing named cycle 21 for four cycles (cycle 25 F26), and cycle 24's block
// was still interleaved with cycle 25's in STATE when cycle 25's expansion
// batches ran. The rule this encodes is the counts block's: the standing is
// DERIVED from `.cycle/metrics.csv` (one row per /reflect) and STATE's `Cycle:`
// line, and CI fails when it has drifted.
//
//   node scripts/cycle-closeout.mjs              dry run: what --write would change
//   node scripts/cycle-closeout.mjs --write      apply the PROJECT_HEALTH update
//   node scripts/cycle-closeout.mjs --check      exit 1 if anything is owed (CI)
//   node scripts/cycle-closeout.mjs --close      preview closing STATE's cycle
//   node scripts/cycle-closeout.mjs --close --write
//        move STATE's whole cycle into HISTORY.md (newest first), reset STATE
//        from the CLAUDE.md template — carrying Pending, Open follow-on items
//        and Decisions bullets that are not struck through — and update
//        PROJECT_HEALTH. Refused unless STATE's phase is reflect or idle and
//        metrics.csv has the cycle's reflect row. Run it as /reflect's last step.
//
//   --root <dir>   operate on another tree (the harness drives fixtures)
//   --today <date> the date written into a reset STATE (default: today)
//
// What PROJECT_HEALTH gets: (1) a Score History row for every cycle metrics.csv
// has reflected and the table lacks — existing rows are never rewritten, the
// hand-written ones carry more than a CSV row can; (2) the region between the
// `closeout:begin` / `closeout:end` markers in Current Standing: the cycle
// STATE is in and the last closed cycle's tally. Everything else in the file is
// prose and stays the author's.
// ─────────────────────────────────────────────────────────────────────────────
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const args = process.argv.slice(2);
const flag = (f) => args.includes(f);
const opt = (f) => { const i = args.indexOf(f); return i >= 0 ? args[i + 1] : undefined; };
const ROOT = path.resolve(opt('--root') || path.join(path.dirname(fileURLToPath(import.meta.url)), '..'));
const P = {
  metrics: path.join(ROOT, '.cycle', 'metrics.csv'),
  state: path.join(ROOT, '.cycle', 'STATE.md'),
  history: path.join(ROOT, '.cycle', 'HISTORY.md'),
  blocks: path.join(ROOT, '.cycle', 'blocks'),
  health: path.join(ROOT, 'PROJECT_HEALTH.md'),
  claude: path.join(ROOT, 'CLAUDE.md'),
};
// HISTORY blocks are checked from this cycle on — older blocks were archived
// under headings no rule matches (`## Cycle 9 — batch 2`, a "superseded header"),
// and they are closed; the rule is for the cycles that close from here.
const HISTORY_FROM = '20';
const BEGIN = '<!-- closeout:begin — generated by scripts/cycle-closeout.mjs from .cycle/metrics.csv and .cycle/STATE.md; do not hand-edit -->';
const END = '<!-- closeout:end -->';

function fail(msg) { process.stderr.write('cycle-closeout: ' + msg + '\n'); process.exit(2); }
const read = (p) => { try { return fs.readFileSync(p, 'utf8'); } catch (e) { fail('cannot read ' + path.relative(ROOT, p)); } };

// RFC 4180: quoted fields may hold commas, doubled quotes and newlines.
function parseCsv(text) {
  const rows = []; let row = []; let f = ''; let q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { f += '"'; i++; } else q = false; }
      else f += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(f); f = ''; if (row.some((x) => x !== '')) rows.push(row); row = [];
    } else f += c;
  }
  row.push(f); if (row.some((x) => x !== '')) rows.push(row);
  const head = rows.shift() || [];
  return rows.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] || '').trim()])));
}

// 19pre < 19 < 19post < 20.
function cycleRank(id) {
  const m = /^(\d+)(pre|post)?$/.exec(String(id).trim());
  if (!m) return NaN;
  return Number(m[1]) * 10 + (m[2] === 'pre' ? -5 : m[2] === 'post' ? 5 : 0);
}

const MINUS = '−';
const signed = (n) => (n > 0 ? '+' + n : n < 0 ? MINUS + Math.abs(n) : '0');
const plural = (n, one, many) => n + ' ' + (n === 1 ? one : many);
const num = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };

// The LAST reflect row per cycle (cycle 19 was reflected five times).
function reflections(metricsText) {
  const by = new Map();
  for (const r of parseCsv(metricsText)) {
    if (r.phase !== 'reflect' || !r.cycle) continue;
    if (Number.isNaN(cycleRank(r.cycle))) fail('metrics.csv: unreadable cycle id "' + r.cycle + '"');
    by.set(r.cycle, r);
  }
  return [...by.values()].sort((a, b) => cycleRank(a.cycle) - cycleRank(b.cycle));
}

function tally(r) {
  const parts = [plural(num(r.prod_fixes), 'prod fix', 'prod fixes') + ' ' + MINUS + ' ' +
    plural(num(r.new_failure_modes), 'new failure mode', 'new failure modes')];
  if (r.defensive_count !== '' && r.defensive_count != null) parts.push(num(r.defensive_count) + ' defensive');
  return 'net ' + signed(num(r.net_score)) + ' (' + parts.join('; ') + ')';
}

function firstSentence(s) {
  const m = /^(.+?[.!?])(\s|$)/.exec(s || '');
  let t = (m ? m[1] : (s || '')).trim();
  if (t.length > 300) t = t.slice(0, 299).trimEnd() + '…';
  return t;
}

function reflectBlock(cycle) {
  let names = [];
  try { names = fs.readdirSync(P.blocks); } catch (e) { /* no blocks dir */ }
  const re = new RegExp('^' + cycle.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '-[a-z]+-reflect\\.md$');
  const hit = names.filter((n) => re.test(n)).sort().pop();
  return hit ? '`.cycle/blocks/' + hit + '`' : 'none on disk';
}

function historyRow(r) {
  const note = (firstSentence(r.notes) + (r.axis_b_lowest ? ' Axis-B lowest: ' + r.axis_b_lowest + '.' : '') +
    ' Reflect block: ' + reflectBlock(r.cycle) + '.').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
  return '| ' + r.date + ' | ' + r.cycle + ' | ' + tally(r) + ' | ' + note + ' |';
}

function stateField(state, name) {
  const m = new RegExp('^' + name + ':[ \\t]*(.*)$', 'm').exec(state);
  return m ? m[1].trim() : '';
}
const stateCycle = (state) => (/^(\d+(?:pre|post)?)\b/.exec(stateField(state, 'Cycle')) || [])[1] || '';
const statePhase = (state) => (/^([a-z]+)/i.exec(stateField(state, 'Phase')) || [])[1] || '';

function region(stateCyc, last) {
  const closed = last && last.cycle === stateCyc;
  const now = closed
    ? '**Now: cycle ' + stateCyc + ' is closed** (reflected ' + last.date + ') — the next audit opens the next cycle.'
    : '**Now: cycle ' + stateCyc + ' is open** (`.cycle/STATE.md`).';
  const lines = [BEGIN, now];
  if (last) {
    lines.push('**Last closed cycle: ' + last.cycle + ', reflected ' + last.date + ' — ' + tally(last) + '.**' +
      (last.axis_b_lowest ? ' Axis-B lowest: ' + last.axis_b_lowest + '.' : '') +
      ' Reflect block: ' + reflectBlock(last.cycle) + '; every reflected cycle is a row of the Score History below.');
  }
  lines.push(END);
  return lines.join('\n');
}

// The new PROJECT_HEALTH text, and what changed.
function planHealth(health, refl, stateCyc) {
  const changes = [];
  let out = health;
  const b = out.indexOf(BEGIN.slice(0, 22));
  const e = out.indexOf(END);
  if (b < 0 || e < b) return { out, changes, error: 'PROJECT_HEALTH.md has no closeout:begin / closeout:end region in Current Standing' };
  const want = region(stateCyc, refl[refl.length - 1]);
  if (out.slice(b, e + END.length) !== want) { out = out.slice(0, b) + want + out.slice(e + END.length); changes.push('Current Standing: the generated region'); }

  const hi = out.indexOf('\n## Score History');
  if (hi < 0) return { out, changes, error: 'PROJECT_HEALTH.md has no "## Score History" section' };
  const lines = out.split('\n');
  const start = out.slice(0, hi + 1).split('\n').length - 1;
  let last = -1; const have = new Set();
  for (let i = start + 1; i < lines.length; i++) {
    if (/^##\s/.test(lines[i])) break;
    if (!lines[i].startsWith('|')) continue;
    last = i;
    const cells = lines[i].split(/(?<!\\)\|/).map((c) => c.trim());
    if (cells[2] && !/^-+$/.test(cells[2]) && cells[2] !== 'Cycle') have.add(cells[2]);
  }
  if (last < 0) return { out, changes, error: 'the Score History table is empty or missing' };
  const add = refl.filter((r) => !have.has(r.cycle)).map(historyRow);
  if (add.length) {
    lines.splice(last + 1, 0, ...add);
    out = lines.join('\n');
    add.forEach((row) => changes.push('Score History: + ' + row.slice(0, 90) + (row.length > 90 ? '…' : '')));
  }
  return { out, changes, error: null };
}

function historyHas(history, cycle) {
  return new RegExp('^#{1,2} Cycle ' + cycle + '(?![0-9a-z])', 'm').test(history);
}

function owedHistory(history, refl, stateCyc) {
  const sr = cycleRank(stateCyc);
  return refl.filter((r) => cycleRank(r.cycle) >= cycleRank(HISTORY_FROM) && cycleRank(r.cycle) < sr && !historyHas(history, r.cycle))
    .map((r) => r.cycle);
}

// ── STATE reset (--close) ───────────────────────────────────────────────────
function sections(md) {
  const out = new Map(); let cur = null;
  for (const l of md.split('\n')) {
    const m = /^##\s+(.*)$/.exec(l);
    if (m) { cur = m[1].trim(); out.set(cur, []); continue; }
    if (cur) out.get(cur).push(l);
  }
  return out;
}
const sectionFor = (secs, prefix) => { for (const [k, v] of secs) if (k.toLowerCase().startsWith(prefix.toLowerCase())) return v; return []; };

// Top-level bullets and their indented continuation lines; a bullet whose text
// opens struck through (`- ~~…`) is finished and stays in HISTORY only.
function carried(lines) {
  const items = []; let cur = null;
  for (const l of lines) {
    if (/^- /.test(l)) { cur = [l]; items.push(cur); }
    else if (cur && /^\s+\S/.test(l)) cur.push(l);
    else cur = null;
  }
  return items.filter((it) => !/^- ~~/.test(it[0])).map((it) => it.join('\n'));
}

function template(claude) {
  const i = claude.indexOf('`.cycle/STATE.md` template:');
  if (i < 0) fail('CLAUDE.md has no "`.cycle/STATE.md` template:"');
  const m = /```\n([\s\S]*?)\n```/.exec(claude.slice(i));
  if (!m) fail('CLAUDE.md: the STATE template has no fenced block');
  return m[1];
}

function resetState(claude, state, r, today) {
  const secs = sections(state);
  const carry = (p) => { const c = carried(sectionFor(secs, p)); return c.length ? c : ['- (none)']; };
  const pend = carry('Pending'), fol = carry('Open follow-on'), dec = carry('Decisions');
  const keep = (name) => stateField(state, name);
  const fields = {
    Cycle: r.cycle + ' — closed ' + r.date + ' (reflected ' + tally(r) + '). The next /broad-scan, /audit or /targeted-audit opens the next cycle.',
    Phase: 'idle',
    Scope: '—',
    'Test Command': keep('Test Command') || 'manual',
    Estimates: '(none yet — each batch\'s goes here before its first edit)',
    'Subsystem cycles since last Seams audit': keep('Subsystem cycles since last Seams audit') || '0',
    Updated: today + ' (close-out of cycle ' + r.cycle + ' by scripts/cycle-closeout.mjs)',
  };
  const body = { 'In progress': ['- (none — cycle ' + r.cycle + ' is closed; its record is the top block of `.cycle/HISTORY.md`)'],
    'Completed this cycle': ['- (none yet)'], 'Pending': pend, 'Open follow-on': fol, 'Decisions': dec,
    'Where I left off': ['Cycle ' + r.cycle + ' was closed on ' + today + ' by `scripts/cycle-closeout.mjs --close`. Next: an audit opens the next cycle; the carried Pending items are the operator\'s open steps.'] };
  const out = []; let skip = false;
  for (const l of template(claude).split('\n')) {
    const h = /^##\s+(.*)$/.exec(l);
    if (h && h[1] !== 'Current') {
      out.push(l, ...(Object.entries(body).find(([k]) => h[1].startsWith(k)) || [null, []])[1], '');
      skip = true; continue;
    }
    if (skip && !/^#/.test(l)) continue;
    skip = false;
    const f = /^([A-Za-z][A-Za-z ]*?):/.exec(l);
    out.push(f && fields[f[1]] != null ? f[1] + ': ' + fields[f[1]] : l);
  }
  while (out.length && out[out.length - 1] === '') out.pop();
  return { text: out.join('\n') + '\n', counts: [pend, fol, dec].map((c) => (c[0] === '- (none)' ? 0 : c.length)) };
}

function historyBlock(state, r, counts) {
  const from = state.indexOf('## Current');
  const body = (from >= 0 ? state.slice(from) : state).replace(/\s+$/, '');
  return ['# Cycle ' + r.cycle + ' (closed ' + r.date + ' — reflected ' + tally(r) + '; moved by `scripts/cycle-closeout.mjs`)', '',
    '**Close-out note.** Reflected ' + r.date + ': ' + tally(r) + '.' + (r.axis_b_lowest ? ' Axis-B lowest: ' + r.axis_b_lowest + '.' : '') +
    ' Reflect block: ' + reflectBlock(r.cycle) + '. Carried into the fresh STATE: ' + plural(counts[0], 'pending item', 'pending items') + ', ' +
    plural(counts[1], 'follow-on', 'follow-ons') + ', ' + plural(counts[2], 'decision', 'decisions') +
    ' (a struck-through item stays here only). The STATE below is verbatim.', '', body, '', '---', ''].join('\n');
}

// ── main ────────────────────────────────────────────────────────────────────
const refl = reflections(read(P.metrics));
const state = read(P.state);
const stateCyc = stateCycle(state);
if (!stateCyc) fail('.cycle/STATE.md has no readable "Cycle:" line');
const lastRefl = refl[refl.length - 1];
if (lastRefl && cycleRank(lastRefl.cycle) > cycleRank(stateCyc)) {
  fail('metrics.csv reflects cycle ' + lastRefl.cycle + ' but STATE.md is on cycle ' + stateCyc);
}
let history = read(P.history);
const health = read(P.health);
const write = flag('--write');

if (flag('--close')) {
  const phase = statePhase(state);
  const r = refl.find((x) => x.cycle === stateCyc);
  if (!/^(reflect|idle)$/.test(phase)) fail('cycle ' + stateCyc + ' is in phase "' + phase + '" — close a cycle after its /reflect');
  if (!r) fail('metrics.csv has no reflect row for cycle ' + stateCyc + ' — run /reflect first');
  if (historyHas(history, stateCyc)) fail('HISTORY.md already has a "Cycle ' + stateCyc + '" block — this cycle is closed');
  const today = opt('--today') || new Date().toLocaleDateString('sv-SE');
  const { text, counts } = resetState(read(P.claude), state, r, today);
  const block = historyBlock(state, r, counts);
  const anchor = /\n---\n\n?/.exec(history);
  if (!anchor) fail('HISTORY.md has no "---" under its header to insert below');
  const at = anchor.index + anchor[0].length;
  const newHistory = history.slice(0, at) + (anchor[0].endsWith('\n\n') ? '' : '\n') + block + '\n' + history.slice(at);
  const ph = planHealth(health, refl, stateCyc);
  if (ph.error) fail(ph.error);
  console.log('close cycle ' + stateCyc + ': HISTORY.md + its block (' + block.split('\n').length + ' lines); STATE.md reset — carried ' +
    counts[0] + ' pending, ' + counts[1] + ' follow-ons, ' + counts[2] + ' decisions');
  ph.changes.forEach((c) => console.log('  PROJECT_HEALTH: ' + c));
  if (!write) { console.log('(preview — add --write to apply)'); process.exit(0); }
  fs.writeFileSync(P.history, newHistory);
  fs.writeFileSync(P.state, text);
  if (ph.out !== health) fs.writeFileSync(P.health, ph.out);
  console.log('written.');
  process.exit(0);
}

const ph = planHealth(health, refl, stateCyc);
const owed = owedHistory(history, refl, stateCyc);
const problems = [];
if (ph.error) problems.push(ph.error);
ph.changes.forEach((c) => problems.push('PROJECT_HEALTH.md is behind metrics.csv / STATE.md — ' + c));
owed.forEach((c) => problems.push('cycle ' + c + ' is reflected and STATE is on ' + stateCyc + ', but HISTORY.md has no "Cycle ' + c +
  '" block — its close-out move is owed (`--close --write` at the cycle\'s close; by hand once a later cycle has opened)'));

if (flag('--check')) {
  if (!problems.length) { console.log('cycle-closeout: in step (cycle ' + stateCyc + '; last reflected ' + (lastRefl ? lastRefl.cycle : 'none') + ')'); process.exit(0); }
  problems.forEach((p) => console.error('cycle-closeout: ' + p));
  console.error('Fix: node scripts/cycle-closeout.mjs --write  (the HISTORY move is --close --write, run as /reflect\'s last step)');
  process.exit(1);
}
if (!problems.length) { console.log('nothing to do (cycle ' + stateCyc + ')'); process.exit(0); }
problems.forEach((p) => console.log(p));
if (write && !ph.error && ph.out !== health) { fs.writeFileSync(P.health, ph.out); console.log('PROJECT_HEALTH.md written.'); }
else if (!write) console.log('(dry run — add --write to apply the PROJECT_HEALTH update)');
